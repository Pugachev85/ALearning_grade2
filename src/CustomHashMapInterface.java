

public interface CustomHashMapInterface <K, V> {

    /**
     * Добавляет пару «ключ‑значение» в коллекцию.
     * Если ключ уже существует, значение обновляется.
     *
     * @param key ключ (может быть null)
     * @param value значение (может быть null)
     */
    void put(K key, V value);

    /**
     * Возвращает значение по заданному ключу.
     *
     * @param key ключ для поиска
     * @return значение, связанное с ключом, или null, если ключ не найден
     */
    V get(K key);

    /**
     * Удаляет элемент с указанным ключом.
     *
     * @param key ключ для удаления
     */
    void remove(K key);

    /**
     * Проверяет наличие ключа в коллекции.
     *
     * @param key ключ для проверки
     * @return true, если ключ присутствует
     */
    boolean containsKey(K key);

    /**
     * Возвращает количество элементов в коллекции.
     *
     * @return число пар «ключ‑значение»
     */
    int size();

    /**
     * Проверяет, пуста ли коллекция.
     *
     * @return true, если коллекция не содержит элементов
     */
    boolean isEmpty();

    /**
     * Возвращает строковое представление коллекции в формате {k1=v1, k2=v2}.
     *
     * @return строка с содержимым коллекции
     */
    String toString();
}